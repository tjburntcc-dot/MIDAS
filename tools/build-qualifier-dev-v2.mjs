/**
 * Dev set v2: the existing development cases re-expressed in the v4 gold format.
 *
 * Decisions, disqualifiers and required-missing are carried over unchanged. Only
 * the numeric gold is regenerated, by the same declared rules used for the sealed
 * v2 instrument, so the defective "declined means unknowable" encoding is gone
 * from the development set too.
 *
 * This exists so frontier model selection can happen on development cases rather
 * than on the sealed instrument. Choosing a baseline model by its sealed score
 * would be selection on the test set.
 */
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { repoPath } from "@midas/db";

const CATEGORY_BANDS = {
  content_small: { ai: [70, 100], human: [30, 240] },
  content_large: { ai: [70, 100], human: [60, 600] },
  data:          { ai: [80, 100], human: [30, 300] },
  automation:    { ai: [65, 100], human: [45, 360] },
  site_small:    { ai: [50, 90],  human: [60, 480] },
  site_large:    { ai: [50, 90],  human: [240, 1200] },
  out_of_scope:  null,
  unstated:      null,
};
const SCOPE_MARKET_RANGES = { site_small: [1200, 6000], content_small: [500, 2500] };

/** Category per existing development case, assigned from its stated scope. */
const CATEGORY = {
  "OQ-D01": "site_small", "OQ-D02": "content_small", "OQ-D03": "automation",
  "OQ-D04": "unstated", "OQ-D05": "unstated", "OQ-D06": "unstated",
  "OQ-D07": "site_large", "OQ-D08": "site_large", "OQ-D09": "out_of_scope",
  "OQ-D10": "content_small", "OQ-D11": "site_large", "OQ-D12": "site_small",
  "OQ-D13": "site_large", "OQ-D14": "content_small", "OQ-D15": "site_small",
  "OQ-D16": "content_small",
};
/** Cases where no budget is stated but the scope implies a market range. */
const SCOPE_INFER = { "OQ-D15": "site_small" };

function deriveNumeric(c) {
  const out = {};
  const b = c.facts.posted_budget_usd;
  if (b != null) {
    out.estimated_value_usd = { band: { low: Math.round(b * 0.75), high: Math.round(b * 1.25) }, source: "stated_budget" };
  } else if (SCOPE_INFER[c.case_id]) {
    const [lo, hi] = SCOPE_MARKET_RANGES[SCOPE_INFER[c.case_id]];
    out.estimated_value_usd = { band: { low: lo, high: hi }, source: "scope_inferred" };
  } else {
    out.estimated_value_usd = { unknowable: true, why: "No figure is stated and the scope does not imply a market range." };
  }
  const cat = CATEGORY_BANDS[CATEGORY[c.case_id]];
  if (!cat) {
    const why = CATEGORY[c.case_id] === "out_of_scope"
      ? "The work sits outside the capability boundary, so our fulfilment share of it is not a meaningful quantity."
      : "The scope is not stated, so effort cannot be decomposed.";
    out.ai_fulfillment_pct = { unknowable: true, why };
    out.human_minutes = { unknowable: true, why };
  } else {
    out.ai_fulfillment_pct = { band: { low: cat.ai[0], high: cat.ai[1] }, source: "scope_inferred" };
    out.human_minutes = { band: { low: cat.human[0], high: cat.human[1] }, source: "scope_inferred" };
  }
  return out;
}

const v1 = JSON.parse(readFileSync(repoPath("evals", "opportunity-qualifier", "v1", "dev_cases_v1.json"), "utf8"));
const cases = v1.cases.map((c) => {
  if (!CATEGORY[c.case_id]) throw new Error("no category assigned for " + c.case_id);
  return {
    case_id: c.case_id, title: c.title, source: c.source, brief: c.brief,
    facts: c.facts, evidence: c.evidence, category: CATEGORY[c.case_id],
    gold: {
      decision: c.gold.decision,
      disqualifiers: c.gold.disqualifiers,
      required_missing: c.gold.required_missing,
      numeric: deriveNumeric(c),
    },
  };
});

const doc = {
  id: "hemmer-opportunity-qualifier-dev-v2", version: "hemmer-opportunity-qualifier-dev-v2",
  specVersion: "v4", derivedFrom: v1.version, synthetic: true, n: cases.length,
  note: "Development cases with numeric gold regenerated by the sealed v2 rules. Decisions and disqualifiers unchanged from v1.",
  cases,
};
const path = repoPath("evals", "opportunity-qualifier", "v2", "dev_cases_v2.json");
mkdirSync(repoPath("evals", "opportunity-qualifier", "v2"), { recursive: true });
writeFileSync(path, JSON.stringify(doc, null, 2) + "\n", "utf8");
const sha = createHash("sha256").update(readFileSync(path)).digest("hex");
console.log("dev v2", cases.length, "cases", sha.slice(0, 16));
