export function createExistingBusiness(store, payload) {
  const preparedDocs = prepareDocuments(payload || {});
  const intake = buildExistingBusinessIntake(payload || {}, preparedDocs);
  const fields = intake.fields;
  const now = intake.capturedAt;
  const id = nextWorkspaceId(store);
  const offerText = fields.existingOffer.value;
  const workspace = putOwnerWorkspace(store, {
    id: id,
    name: fields.companyName.value,
    nameSource: "owner_provided",
    description: fields.businessDescription.value,
    industry: null,
    type: null,
    offer: offerText ? { name: null, summary: offerText } : null,
    idealCustomer: fields.customerProfile.value,
    geography: null,
    goal: fields.goals.value,
    constraints: fields.ownerConstraints.value ? [fields.ownerConstraints.value] : [],
    createdAt: now,
    updatedAt: now,
    ownerStatus: "active",
    assignedAgentId: null,
    assignedRoleId: null,
    epistemicClass: "business_description",
    persistence: "FILE_STORE",
    origin: "owner_intake",
    intakeKind: "existing_business",
    applicationIsolation: true,
    isolationKind: "application-level",
    servingAtlasVersionId: null,
    teamGenerated: false,
    opportunitiesInvented: false,
    intake: intake,
  });
  const savedDocs = persistIntakeDocuments(store, workspace.id, preparedDocs);
  const savedProc = persistProcedures(store, workspace.id, fields.existingProcedures.value);
  if (savedDocs.length || savedProc) {
    const nextIntake = {
      ...intake,
      documents: savedDocs,
      procedures: savedProc,
      trainingStudioLink: { href: "#/training", label: "Open Training Studio to assign these documents later" },
    };
    workspace.intake = nextIntake;
    workspace.updatedAt = nowIso();
    store.putWorkspace(workspace);
  }
  return {
    ok: true,
    persistence: "FILE_STORE",
    honesty: INTAKE_HONESTY,
    isolation: isolationView(store.getWorkspace(workspace.id), { employees: [], knowledge: [], teachingPackets: [], spendEntries: 0 }),
    workspace: store.getWorkspace(workspace.id),
    company: { id: workspace.id, name: workspace.name, intakeKind: "existing_business" },
    intake: presentIntake(store.getWorkspace(workspace.id)),
    documents: savedDocs,
    procedures: savedProc,
    trainingStudioLink: (savedDocs.length || savedProc) ? { href: "#/training", label: "Open Training Studio to assign these documents later" } : null,
    ...assertNoLiveSideEffects(),
    note: "Real FILE_STORE workspace from owner-supplied facts only. Documents stay on this workspace and can be assigned in Training Studio.",
  };
}
