function buildNewBusinessIntake(payload) {
  const companyName = ownerField(payload && payload.companyName);
  const ownerObjective = ownerField(payload && (payload.ownerObjective || payload.objective));
  if (!companyName.value && !ownerObjective.value) {
    const err = new Error("A company name or an owner objective is required. Missing fields are not invented.");
    err.code = "INTAKE_REQUIRED";
    throw err;
  }
  return {
    kind: "new_business",
    capturedAt: nowIso(),
    fields: {
      companyName: companyName,
      ownerObjective: ownerObjective,
      revenueGoal: ownerField(payload && payload.revenueGoal, { epistemic: "owner_stated_goal", notAForecast: true }),
      budget: ownerField(payload && payload.budget),
      timeline: ownerField(payload && payload.timeline),
      preferredIndustries: ownerField(payload && (payload.preferredIndustries || payload.industries || payload.interests), { list: true }),
      availableSkillsAndResources: ownerField(payload && (payload.availableSkillsAndResources || payload.skills || payload.resources)),
      geographicConstraints: ownerField(payload && (payload.geographicConstraints || payload.geography)),
      riskTolerance: ownerField(payload && payload.riskTolerance),
      permittedResearchScope: ownerField(payload && payload.permittedResearchScope),
      ownerApprovalRequirements: ownerField(payload && payload.ownerApprovalRequirements),
    },
    documents: [],
    procedures: null,
    trainingStudioLink: null,
  };
}

