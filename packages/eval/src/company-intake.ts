function normalizeDocuments(payload) {
  const out = [];
  const push = (doc) => {
    if (!doc) return;
    if (typeof doc === "string") {
      if (doc.trim()) out.push({ title: "Owner document", text: doc.trim(), sourceType: "owner_paste", filename: null, pdfBase64: null });
      return;
    }
    out.push({
      title: asText(doc.title) || "Owner document",
      text: asText(doc.text || doc.markdown || doc.body),
      sourceType: asText(doc.sourceType) || (doc.pdfBase64 ? "owner_pdf" : "owner_paste"),
      filename: asText(doc.filename) || null,
      pdfBase64: doc.pdfBase64 || null,
    });
  };
  const docs = payload && (payload.existingDocuments || payload.documents);
  if (typeof docs === "string") push(docs);
  else if (Array.isArray(docs)) for (const d of docs) push(d);
  if (payload && asText(payload.existingDocumentsText)) {
    push({
      title: asText(payload.existingDocumentsTitle) || "Owner document",
      text: payload.existingDocumentsText,
      sourceType: asText(payload.existingDocumentsSourceType) || "owner_markdown",
      filename: asText(payload.existingDocumentsFilename) || null,
      pdfBase64: payload.existingDocumentsPdfBase64 || null,
    });
  }
  if (payload && payload.existingDocumentsPdfBase64 && !asText(payload.existingDocumentsText) && !(Array.isArray(docs) && docs.length)) {
    push({
      title: asText(payload.existingDocumentsTitle) || "Owner document",
      sourceType: "owner_pdf",
      filename: asText(payload.existingDocumentsFilename) || null,
      pdfBase64: payload.existingDocumentsPdfBase64,
    });
  }
  return out;
}

function prepareDocuments(payload) {
  const prepared = [];
  for (const d of normalizeDocuments(payload)) {
    let text = d.text || "";
    let sourceType = d.sourceType || "owner_paste";
    let pdfNote = null;
    if (d.pdfBase64) {
      const parsed = extractPdf(d.pdfBase64);
      pdfNote = parsed.note;
      if (!parsed.ok) {
        const err = new Error(parsed.note || "PDF not parsed.");
        err.code = "PDF_PARSE";
        throw err;
      }
      text = parsed.text;
      sourceType = "owner_pdf";
    }
    if (!String(text).trim()) continue;
    const leaks = leakScan(text);
    if (leaks.length) {
      const err = new Error("Document rejected by leak scan: " + leaks.join(","));
      err.code = "LEAK";
      throw err;
    }
    prepared.push({
      title: d.title || "Owner document",
      text: String(text).trim(),
      sourceType: sourceType,
      filename: d.filename || null,
      pdfNote: pdfNote,
    });
  }
  return prepared;
}

function persistBytes(id, text) {
  const dir = join(defaultCurriculumRoot(), "sources", id);
  mkdirSync(dir, { recursive: true });
  const sha = sha256Text(text);
  const bytesPath = join(dir, sha);
  if (!existsSync(bytesPath)) writeFileSync(bytesPath, text, "utf8");
  return { sha: sha, bytesPath: bytesPath, byteLength: Buffer.byteLength(text, "utf8") };
}

function persistIntakeDocuments(store, workspaceId, docs) {
  const saved = [];
  if (!docs || !docs.length) return saved;
  const existingIds = [
    ...((store.listTrainingStudioRecords && store.listTrainingStudioRecords()) || []).map((r) => r.id),
    ...((store.listKnowledge && store.listKnowledge()) || []).map((k) => k.id),
    ...((store.listSources && store.listSources()) || []).map((s) => s.id),
  ];
  for (const doc of docs) {
    const now = nowIso();
    const recordId = nextId(existingIds, "TSR-");
    existingIds.push(recordId);
    const sourceId = nextId(existingIds, "SRC-INTAKE-");
    existingIds.push(sourceId);
    const bytes = persistBytes(sourceId, doc.text);
    const classification = "company_fact";
    if (store.putSource) {
      store.putSource({
        id: sourceId,
        url: "midas://intake/" + recordId,
        title: doc.title,
        publisher: "MIDAS owner intake",
        retrievedAt: now,
        contentType: doc.sourceType === "owner_markdown" ? "text/markdown" : (doc.sourceType === "owner_pdf" ? "application/pdf" : "text/plain"),
        sha256: bytes.sha,
        byteLength: bytes.byteLength,
        parserVersion: "midas-company-intake-v0.1.0",
        captureStatus: "OWNER_AUTHORED",
        captureNote: "Owner-supplied intake document. Not copied from another workspace.",
        bytesPath: bytes.bytesPath,
        runtimeEligible: true,
        studio: true,
        trainingStudio: true,
        sourceType: doc.sourceType,
        classification: classification,
        workspaceId: workspaceId,
      });
    }
    const claims = extractClaims(doc.text);
    const itemIds = [];
    for (const c of claims) {
      const itemId = nextId(existingIds, "K-INTAKE-");
      existingIds.push(itemId);
      itemIds.push(itemId);
      store.putKnowledge({
        id: itemId,
        type: "decision_rule",
        statement: c.statement,
        sourceId: sourceId,
        sourceSha256: bytes.sha,
        locator: { section: "Intake", charStart: 0, charEnd: String(c.excerpt || "").length, text: c.excerpt },
        claimKind: "product_behavior",
        kind: classification,
        classification: classification,
        epistemicClass: classification,
        accepted: true,
        createdAt: now,
        runtimeEligible: true,
        studio: true,
        reviewStatus: "approved",
        writtenByOwner: true,
        sourceType: doc.sourceType,
        workspaceId: workspaceId,
        workspace: workspaceId,
        excerpt: c.excerpt,
        enteredVersion: false,
        enteredRetrievalIndex: true,
        trainingRecordId: recordId,
        intakeOrigin: true,
      });
    }
    const record = {
      id: recordId,
      workspaceId: workspaceId,
      title: doc.title,
      createdAt: now,
      timestamp: now,
      sourceType: doc.sourceType,
      classification: classification,
      ownerApprovalStatus: "approved",
      targetEmployeeIds: [],
      targetRoleIds: [],
      extractedClaims: itemIds.map((id, i) => ({ id: id, statement: claims[i] && claims[i].statement })),
      enteredVersion: false,
      enteredRetrievalIndex: true,
      intakeOrigin: true,
      trainingStudioHref: "#/training",
      persistence: "FILE_STORE",
      entireDocumentDumpedIntoPrompt: false,
      pdf: doc.pdfNote || null,
      filename: doc.filename || null,
      note: "Stored from company intake. Assign in Training Studio when this company has employees. Not copied from another workspace.",
    };
    store.putTrainingStudioRecord(record);
    saved.push({
      recordId: recordId,
      sourceId: sourceId,
      knowledgeItemIds: itemIds,
      title: doc.title,
      trainingStudioHref: "#/training",
    });
  }
  return saved;
}

function persistProcedures(store, workspaceId, text) {
  const body = asText(text);
  if (!body) return null;
  const leaks = leakScan(body);
  if (leaks.length) {
    const err = new Error("Procedures rejected by leak scan: " + leaks.join(","));
    err.code = "LEAK";
    throw err;
  }
  const existingIds = [
    ...((store.listTrainingStudioRecords && store.listTrainingStudioRecords()) || []).map((r) => r.id),
    ...((store.listKnowledge && store.listKnowledge()) || []).map((k) => k.id),
  ];
  const now = nowIso();
  const recordId = nextId(existingIds, "TSR-");
  const claims = extractClaims(body);
  const itemIds = [];
  for (const c of claims) {
    const itemId = nextId(existingIds.concat(itemIds), "K-INTAKE-");
    itemIds.push(itemId);
    store.putKnowledge({
      id: itemId,
      type: "procedure",
      statement: c.statement,
      sourceId: null,
      sourceSha256: sha256Text(body),
      locator: { section: "Intake procedures", charStart: 0, charEnd: String(c.excerpt || "").length, text: c.excerpt },
      claimKind: "product_behavior",
      kind: "procedure",
      classification: "procedure",
      epistemicClass: "procedure",
      accepted: true,
      createdAt: now,
      runtimeEligible: true,
      reviewStatus: "approved",
      writtenByOwner: true,
      sourceType: "owner_paste",
      workspaceId: workspaceId,
      workspace: workspaceId,
      excerpt: c.excerpt,
      enteredVersion: false,
      enteredRetrievalIndex: true,
      trainingRecordId: recordId,
      intakeOrigin: true,
    });
  }
  const record = {
    id: recordId,
    workspaceId: workspaceId,
    title: "Owner procedures",
    createdAt: now,
    timestamp: now,
    sourceType: "owner_paste",
    classification: "procedure",
    ownerApprovalStatus: "approved",
    targetEmployeeIds: [],
    extractedClaims: itemIds.map((id, i) => ({ id: id, statement: claims[i] && claims[i].statement })),
    enteredVersion: false,
    enteredRetrievalIndex: true,
    intakeOrigin: true,
    trainingStudioHref: "#/training",
    persistence: "FILE_STORE",
    note: "Owner-supplied procedures from intake. Assign in Training Studio when employees exist.",
  };
  store.putTrainingStudioRecord(record);
  return { recordId: recordId, knowledgeItemIds: itemIds, trainingStudioHref: "#/training" };
}

function presentFieldMap(fields) {
  const out = {};
  for (const [key, field] of Object.entries(fields || {})) {
    out[key] = field;
  }
  return out;
}

