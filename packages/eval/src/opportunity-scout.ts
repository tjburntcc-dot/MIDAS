function fieldForCompare(opp, field) {
  if (field === "comparisonDimensions") {
    const dims = opp.comparisonDimensions || {};
    return {
      text: COMPARISON_DIMENSIONS.map((d) => d + ": " + (((dims[d] && dims[d].text) || "unknown"))).join(" · "),
      items: dims,
      claimClass: "model_generated_hypothesis",
      decisionAidOnly: true,
    };
  }
  const v = opp[field];
  if (field === "name") return { text: opp.name, claimClass: opp.nameClaimClass, label: OPPORTUNITY_CLAIM_LABELS[opp.nameClaimClass] || opp.nameClaimClass };
  if (Array.isArray(v)) {
    return {
      text: v.map((x) => (x && x.text) || "").filter(Boolean).join(" · ") || null,
      items: v,
      claimClasses: [...new Set(v.map((x) => x && x.claimClass).filter(Boolean))],
    };
  }
  if (v && typeof v === "object") return v;
  return classified(v == null ? null : String(v), "unknown");
}

