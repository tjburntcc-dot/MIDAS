function claimIndex(draft) {
  const verifiedSourcedFacts = [];
  const vendorOrMarketingClaims = [];
  const modelGeneratedHypotheses = [];
  const ownerProvidedInformation = [];
  const unknownInformation = [];
  const publicSourceObservations = [];
  const estimates = [];
  const walk = (node, path) => {
    if (!node) return;
    if (Array.isArray(node)) {
      node.forEach((n, i) => walk(n, path + "[" + i + "]"));
      return;
    }
    if (typeof node === "object") {
      if (node.claimClass) {
        const row = { path: path, text: node.text, claimClass: node.claimClass, label: node.label };
        if (node.claimClass === "verified_sourced_fact" || node.claimClass === "independent_sourced_fact") verifiedSourcedFacts.push(row);
        else if (node.claimClass === "vendor_or_marketing_claim" || node.claimClass === "vendor_stated_claim") vendorOrMarketingClaims.push(row);
        else if (node.claimClass === "model_generated_hypothesis") modelGeneratedHypotheses.push(row);
        else if (node.claimClass === "owner_provided" || node.claimClass === "owner_provided_fact") ownerProvidedInformation.push(row);
        else if (node.claimClass === "public_source_observation") publicSourceObservations.push(row);
        else if (node.claimClass === "estimate") estimates.push(row);
        else unknownInformation.push(row);
      }
      for (const [k, v] of Object.entries(node)) {
        if (k === "claimClasses" || k === "invented") continue;
        if (typeof v === "object") walk(v, path ? path + "." + k : k);
      }
    }
  };
  walk(draft, "");
  if (draft.nameClaimClass === "model_generated_hypothesis") {
    modelGeneratedHypotheses.unshift({ path: "name", text: draft.name, claimClass: "model_generated_hypothesis", label: OPPORTUNITY_CLAIM_LABELS.model_generated_hypothesis });
  }
  return { verifiedSourcedFacts, vendorOrMarketingClaims, modelGeneratedHypotheses, ownerProvidedInformation, unknownInformation, publicSourceObservations, estimates };
}

