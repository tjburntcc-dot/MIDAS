function difficultyFrom(intake) {
  const risk = asText(intake.riskTolerance);
  const skills = asText(intake.availableSkillsAndResources);
  const timeline = asText(intake.timeline);
  const budget = asText(intake.budget);
  if (!risk && !skills && !timeline && !budget && !asText(intake.constraints)) {
    return {
      value: null,
      text: null,
      claimClass: "unknown",
      label: OPPORTUNITY_CLAIM_LABELS.unknown,
      note: "No owner constraint to judge difficulty from. Left unknown.",
    };
  }
  let value = "medium";
  let note = "Preliminary difficulty is a model-generated hypothesis from owner-stated constraints. Not a researched complexity score.";
  if (/low/.test(risk.toLowerCase())) {
    value = "medium";
    note = "Owner-stated low risk tolerance. Medium first-step difficulty is a hypothesis so the first experiment stays inspectable.";
  } else if (/high/.test(risk.toLowerCase())) {
    value = "high";
    note = "Owner-stated high risk tolerance. High difficulty is a hypothesis, not evidence the work is actually hard.";
  } else if (timeline && /30|week|asap|immediate/i.test(timeline)) {
    value = "medium";
    note = "Owner-stated short timeline. Medium difficulty is a hypothesis about fitting that timeline.";
  }
  return {
    value: value,
    text: value,
    claimClass: "model_generated_hypothesis",
    label: OPPORTUNITY_CLAIM_LABELS.model_generated_hypothesis,
    note: note,
  };
}

